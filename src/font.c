uint8_t font_row(char character, unsigned int row)
{
    if (row >= 7 || character < 32 || character > 126) {
        return 0;
    }

    if (character >= 'A' && character <= 'Z') {
        return (uint8_t)(uppercase[character - 'A'][row] << 3);
    }

    if (character >= 'a' && character <= 'z') {
        return (uint8_t)(punctuation[character - 'a' + 39][row] << 3);
    }

    if (character <= '@') {
        return (uint8_t)(punctuation[character - 32][row] << 3);
    }
    if (character <= '`') {
        return (uint8_t)(punctuation[character - '[' + 33][row] << 3);
    }
    return (uint8_t)(punctuation[character - '{' + 65][row] << 3);
}
